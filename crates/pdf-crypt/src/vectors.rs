fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

#[test]
fn every_digest_at_the_lengths_where_padding_changes() {
    for (n, md5s, sha256s, sha384s, sha512s) in DIGESTS {
        let message: Vec<u8> = (0..n).map(|i| ((i * 31 + 7) % 256) as u8).collect();
        assert_eq!(hex(&md5(&message)), md5s, "MD5, {n} bytes");
        assert_eq!(hex(&sha256(&message)), sha256s, "SHA-256, {n} bytes");
        assert_eq!(hex(&sha384(&message)), sha384s, "SHA-384, {n} bytes");
        assert_eq!(hex(&sha512(&message)), sha512s, "SHA-512, {n} bytes");
    }
}
