//! PDF 2D geometry, bounded graphics and text state interpreter, content
//! re-encoder, and vector/text canvas (ISO 32000-2, §8–§9, §11, §14.6),
//! matching PDFium's content interpretation rules as of chromium/8152.
//!
//! `pdf-gfx` operates over decoded content streams ([`Concat`](pdf_content_streams::Concat)) and any
//! [`Resolve`](pdf_objects::Resolve) + [`Streams`](pdf_objects::Streams)
//! provider without performing file I/O, image pixel decoding, or rasterization.
//!
//! # Core Concepts
//!
//! - **2D geometry & page coordinate spaces ([`Point`], [`Rect`], [`Quad`], [`Matrix`], [`Rotation`], [`PageGeom`]):**
//!   Exact quarter-turn rotations, affine placement ([`Matrix::onto`]), and
//!   closed-form transforms between PDF PageSpace (`y` up, before `/Rotate`)
//!   and viewer ViewSpace (`(0, 0)` at top-left, `y` down, after `/Rotate`).
//! - **Bounded content & Form XObject interpreter ([`interpret`], [`interpret_with`], [`Event`], [`State`]):**
//!   Steps through content streams and nested Form XObjects (`Do`), tracking
//!   the CTM stack (`q`/`Q`/`cm`), line style, active color spaces & patterns,
//!   `ExtGState` parameters (`gs`), paths & stroked bounds ([`PathDrawn`],
//!   [`Seg`]), path/text/form clipping ([`Clip`]), placed images & effective
//!   DPI ([`ImageDrawn`]), shadings ([`ShadingDrawn`]), marked content
//!   ([`Mark`], [`Marks`]), and placed text glyphs ([`TextShow`], [`Glyph`])
//!   under strict per-page [`Limits`].
//! - **Position-independent content re-encoding ([`encode`], [`encode_with`], [`EncodedPage`]):**
//!   Rewrites relative line-moving text operators (`Td`, `TD`, `T*`, `'`, `"`)
//!   into standalone `Tm` + `Td` pairs so lines no longer depend on `TL` or
//!   earlier lines, while round-tripping every placed glyph, path, clip, and
//!   mark bit-for-bit.
//! - **Vector, XObject & text canvas ([`Canvas`], [`TextPiece`]):**
//!   Builds new content streams with scoped `q`/`Q` state, inset borders,
//!   rounded rectangles, ellipses, placed images/Form XObjects, and
//!   `TJ`-kerned text over [`ContentWriter`](pdf_content_streams::ContentWriter).
//! - **Default appearance strings ([`DefaultAppearance`]):**
//!   Parses a `/DA` string (ISO 32000-2, §12.7.4.3) under
//!   [`pdf_content_streams::Limits`] into its font resource name and size
//!   (`Tf`, with `0` kept as auto-size), device color, and text-state scalars
//!   (`Tc`, `Tw`, `Tz`, `TL`, `Tr`, `Ts`), and writes it back deterministically,
//!   so annotations and form fields share one reader and writer.
//! - **Positioned text page, search & multiline layout (`text-layout` feature):**
//!   `TextPage` assembles placed glyphs into reading-order lines with synthetic
//!   spaces and line breaks, faux-bold deduplication, `/ActualText` replacement,
//!   `unicode-bidi` visual-to-logical reordering, soft-hyphen detection,
//!   selection quads, hit-testing, and search; `layout_text` and
//!   `Canvas::text_box` wrap, align, justify, auto-size, and comb-place UTF-8
//!   text over `Std14`, `Font`, or `FontEncoder`.
//!
//! # Cargo Features
//!
//! - **`programs`** *(default)*: Forwards `pdf-fonts/programs` so embedded
//!   TrueType, Type 1, CFF, and OpenType glyph outlines tighten [`Glyph::quad`]
//!   boxes.
//! - **`text-layout`** *(default)*: Enables `TextPage` reading-order assembly,
//!   `unicode-bidi` reordering, selection quads, search, and multiline/box
//!   `layout_text` / `Canvas::text_box` drawing.
//! - **`predefined-cmaps`** *(optional)*: Forwards `pdf-fonts/predefined-cmaps`
//!   for bundled Adobe CJK CMaps and UCS-2 collections.
//! - **`tracing`** *(optional)*: Emits numeric `tracing` spans (byte lengths
//!   only; never file plaintext or names).
//!
//! # Example
//!
//! Draw a clipped banner and positioned text with [`Canvas`], then interpret
//! the resulting content stream and map a glyph box into viewer coordinates:
//!
//! ```
//! use std::collections::BTreeMap;
//! use std::ops::ControlFlow;
//!
//! use pdf_gfx::pdf_content_streams::{Color, Concat, Res, Reserved};
//! use pdf_gfx::pdf_fonts::{Fonts, Std14};
//! use pdf_gfx::pdf_objects::{Object, ObjectId, Unreadable, Why, WithStreams};
//! use pdf_gfx::{Canvas, Kind, Limits, Opts, PageGeom, Point, Rect, Rotation, interpret};
//!
//! // Draw a filled rectangle and a line of Helvetica text onto a Letter page.
//! let mut canvas = Canvas::new();
//! let font = Res::dict(Std14::Helvetica.dict()).unwrap();
//! canvas.with_state(|c| {
//!     c.clip_rect(Rect::from_xywh(36.0, 700.0, 200.0, 60.0));
//!     c.fill_color(Color::rgb8([230, 240, 255]));
//!     c.fill_rect(Rect::from_xywh(36.0, 700.0, 200.0, 60.0));
//! });
//! canvas.text_at(font, 12.0, Point::new(48.0, 720.0), b"Hello");
//! let (bytes, needs) = canvas.finish(&Reserved::default());
//!
//! // Bind the font resource generated by the canvas into `/Resources`.
//! let mut font_res = pdf_gfx::pdf_objects::Dict::new();
//! for need in &needs.0 {
//!     font_res.set(need.name.clone(), Std14::Helvetica.dict());
//! }
//! let mut res_dict = pdf_gfx::pdf_objects::Dict::new();
//! res_dict.set("Font", font_res);
//! let resources = Object::from(res_dict);
//!
//! // Interpret the stream with zero I/O and inspect the placed glyphs.
//! let objects = BTreeMap::<ObjectId, Object>::new();
//! let streams = WithStreams::new(&objects, |id, _| {
//!     Err(Unreadable::new(id, Why::Damaged, "no streams"))
//! });
//! let content = Concat::new(&[&bytes]);
//! let mut glyph_boxes = Vec::new();
//! let summary = interpret(
//!     streams,
//!     &content,
//!     Some(&resources),
//!     &Limits::DEFAULT,
//!     &Fonts::default(),
//!     Opts::default(),
//!     |event| {
//!         if let Kind::Text(show) = event.kind {
//!             glyph_boxes.extend(show.glyphs().map(|g| g.quad.bounds()));
//!         }
//!         ControlFlow::Continue(())
//!     },
//! )
//! .unwrap();
//! assert_eq!(summary.glyphs, 5);
//!
//! // Convert the first glyph's bounding box from PageSpace (`y` up) to ViewSpace (`y` down).
//! let geom = PageGeom::new(Rect::LETTER, None, Rotation::R0);
//! let in_view = geom.to_view().apply_rect(glyph_boxes[0]);
//! assert!(in_view.y0 < 80.0);
//! ```

